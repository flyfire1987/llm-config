# 去重
seen = set()
unique_stocks = []
for c, n in BIG_STOCKS:
    if c not in seen:
        seen.add(c)
        unique_stocks.append((c, n))

BIG_STOCKS = unique_stocks

def get_kline_tencent(code):
    try:
        url = f"https://web.ifzq.gtimg.cn/appstock/app/fqkline/get?_var=kline_dayhfq&param={code},day,,,320,qfq&r=0.1"
        req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0', 'Referer': 'https://finance.qq.com'})
        resp = urllib.request.urlopen(req, timeout=10)
        text = resp.read().decode('utf-8')
        text = text.replace('kline_dayhfq=', '', 1)
        data = json.loads(text)
        days = data.get('data', {}).get(code, {}).get('qfqday', [])
        if not days:
            days = data.get('data', {}).get(code, {}).get('day', [])
        if not days:
            return None
        days_clean = [d[:6] for d in days if len(d) >= 6]
        df = pd.DataFrame(days_clean, columns=['date', 'open', 'close', 'high', 'low', 'volume'])
        for col in ['open', 'close', 'high', 'low', 'volume']:
            df[col] = pd.to_numeric(df[col], errors='coerce')
        return df
    except:
        return None

results = []
print(f"开始筛选{len(BIG_STOCKS)}只大盘股...", flush=True)

for code, name in BIG_STOCKS:
    df_k = get_kline_tencent(code)
    if df_k is None or len(df_k) < 30:
        continue
    
    df_k = df_k.tail(60).copy()
    df_k['ma20'] = df_k['close'].rolling(20).mean()
    
    # 近4日连续下跌(2~4天)
    recent4 = df_k.tail(4)
    if len(recent4) < 4:
        continue
    down_days = sum(1 for i in range(3) if recent4.iloc[-(i+1)]['close'] < recent4.iloc[-(i+2)]['close'])
    if down_days < 2:
        continue
    
    # 缩量
    last_vol = df_k.iloc[-1]['volume']
    prev_vol = df_k.iloc[-2]['volume']
    if last_vol >= prev_vol or prev_vol == 0:
        continue
    
    # 20日线±2%
    ma20 = df_k.iloc[-1]['ma20']
    last_close = df_k.iloc[-1]['close']
    if pd.isna(ma20) or ma20 == 0:
        continue
    dist_ma20 = (last_close - ma20) / ma20 * 100
    if abs(dist_ma20) > 2:
        continue
    
    # 近30日创过阶段新高(30日高点在近25天内创出)
    df_last30 = df_k.tail(30)
    high30 = df_last30['high'].max()
    high_positions = df_last30[df_last30['high'] == high30].index.tolist()
    if not high_positions:
        continue
    high_idx = high_positions[-1]
    days_ago = len(df_k) - 1 - df_k.index.get_loc(high_idx)
    if days_ago > 25:
        continue
    
    # 有效跌破
    broken = "否" if last_close >= ma20 * 0.97 else "是"
    
    # 4日跌幅
    pct_chg_4d = round((last_close / df_k.iloc[-4]['close'] - 1) * 100, 1)
    
    # 成交量活跃度
    avg_vol = df_k['volume'].tail(20).mean()
    vol_ratio = last_vol / avg_vol if avg_vol > 0 else 0
    
    # 综合评分
    score = pct_chg_4d * -1 + abs(dist_ma20) * 0.5 + vol_ratio * 3 - (days_ago * 0.1)
    
    results.append({
        '股票名称': name,
        '代码': code[-6:],
        '回调天数': f"{down_days}天",
        '距20日线': f"{dist_ma20:+.1f}%",
        '是否有效跌破': broken,
        '热门板块': '大盘蓝筹',
        '操作建议': '可低吸' if broken == '否' and dist_ma20 >= -2 else '观望',
        'score': score
    })

results.sort(key=lambda x: x['score'], reverse=True)
top20 = results[:20]

print("\n=== 反弹标的筛选结果 ===\n", flush=True)
if top20:
    print("| 股票名称 | 代码 | 回调天数 | 距20日线 | 是否有效跌破 | 热门板块 | 操作建议 |")
    print("|:--------:|:----:|:--------:|:--------:|:------------:|:--------:|:--------:|")
    for r in top20:
        print(f"| {r['股票名称']} | {r['代码']} | {r['回调天数']} | {r['距20日线']} | {r['是否有效跌破']} | {r['热门板块']} | {r['操作建议']} |")
else:
    print("未筛选到符合条件的股票", flush=True)
print(f"\n共筛选出 {len(top20)} 只", flush=True)
